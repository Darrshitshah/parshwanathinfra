// @vitest-environment jsdom
import { cleanup, render, screen } from "@testing-library/react";
import { afterEach, describe, expect, it } from "vitest";
import { Logo } from "./Logo";
import { LOGO_GAP, LOGO_MARK, LOGO_WORD } from "./logo-data";

afterEach(cleanup);

describe("logo data (generated by brand/logo/_build)", () => {
  it("holds the mark and the wordmark as single outlined paths in the same 100 unit height", () => {
    for (const shape of [LOGO_MARK, LOGO_WORD]) {
      expect(shape.width).toBeGreaterThan(0);
      expect(shape.d).toMatch(/^M[\d.]/);
    }
    // The arch is taller than wide; the name is far wider than the mark.
    expect(LOGO_MARK.width).toBeLessThan(100);
    expect(LOGO_WORD.width).toBeGreaterThan(4 * LOGO_MARK.width);
    expect(LOGO_GAP).toBeGreaterThan(0);
    expect(LOGO_GAP).toBeLessThan(0.5);
  });
});

describe("Logo", () => {
  it("is one named image when given a label, with the mark and the name drawn in currentColor", () => {
    render(<Logo label="Parshwanath Infra" />);
    const logo = screen.getByRole("img", { name: "Parshwanath Infra" });
    const svgs = logo.querySelectorAll("svg");
    expect(svgs).toHaveLength(2);
    for (const svg of svgs) {
      expect(svg).toHaveAttribute("aria-hidden", "true");
      expect(svg.getAttribute("viewBox")).toMatch(/^0 0 [\d.]+ 100$/);
      expect(svg.querySelector("path")).toHaveAttribute("fill", "currentColor");
    }
    // Both parts are 1em tall, so they share the --logo-h height and keep the lockup's alignment.
    const [mark, word] = Array.from(svgs);
    expect(mark.style.height).toBe("1em");
    expect(word.style.height).toBe("1em");
    expect(parseFloat(mark.style.width)).toBeCloseTo(LOGO_MARK.width / 100, 3);
    expect(parseFloat(word.style.width)).toBeCloseTo(LOGO_WORD.width / 100, 3);
    expect(parseFloat(word.style.marginLeft)).toBeCloseTo(LOGO_GAP, 3);
  });

  it("is decorative without a label (the link around it carries the name)", () => {
    const { container } = render(<Logo />);
    expect(container.firstElementChild).toHaveAttribute("aria-hidden", "true");
    expect(screen.queryByRole("img")).toBeNull();
  });

  it("can show the mark alone, or the name only from the sm breakpoint up", () => {
    const { container, rerender } = render(<Logo wordmark={false} markClassName="text-brick-ink" />);
    expect(container.querySelectorAll("svg")).toHaveLength(1);
    expect(container.querySelector("svg")).toHaveClass("text-brick-ink");
    rerender(<Logo wordmark="sm" />);
    const word = container.querySelectorAll("svg")[1];
    expect(word).toHaveClass("hidden", "sm:block");
  });
});
