"""Build the white-clay model of Shiv Shiva Township from src/content/plan/plan.json (owner: scene-lead).

    tools/.venv-blender/bin/python tools/blender/build_scene.py

Writes `_source/blender/shiv-shiva.blend` (gitignored) and `src/features/diorama/scene-meta.json` (model frame and
per-building heights, read by the web component). Re-run whenever plan.json changes. Floors: plan.json `floors` when it is
a number, else the confirmed counts in common.py (flats, mixed use, shops A: 6 levels; row houses: 2 storeys), each with a
roof terrace and 1.1 m parapet.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import bpy

import build_ground
import build_town
from common import BLEND_PATH, META_PATH, Frame, clay_materials, clean_ring, load_plan


def reset() -> None:
    bpy.ops.wm.read_factory_settings(use_empty=True)


def collection(name: str):
    c = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(c)
    return c


def main() -> None:
    t0 = time.time()
    plan = load_plan()
    frame = Frame(plan)
    reset()
    mats = clay_materials()
    ground, lawns, town, amen, trees, cars, details = (collection(n) for n in
        ("Ground", "Lawns", "Buildings", "Amenities", "Trees", "Cars", "Details"))

    build_ground.build_ground(plan, frame, mats, ground)
    build_ground.build_lawns(plan, frame, mats, lawns)
    _, round_info = build_ground.build_roundabout(plan, frame, mats, details, mats["brick"])
    building_info = build_town.build_buildings(plan, frame, mats, town)
    n_plots = build_town.build_plots(plan, frame, mats, town)
    amenity_info = build_town.build_amenities(plan, frame, mats, amen)
    build_town.build_entries(plan, frame, mats, details)
    roads_lines = [frame.pts(r["centerline"]) for r in plan["roads"]]
    keep_out = [clean_ring(frame.pts(a["polygon"])) for a in plan["amenities"] if a.get("polygon") and a["kind"] != "garden"]
    n_trees = build_town.build_trees(plan, frame, mats, trees, keep_out, roads_lines)
    n_cars = build_town.build_cars(plan, frame, mats, cars, round_info)

    BLEND_PATH.parent.mkdir(parents=True, exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=str(BLEND_PATH))

    x0, y0, x1, y1 = build_ground.rect_metres(frame)
    meta = {
        "note": "Generated by tools/blender/build_scene.py. Floors confirmed: flats, mixed use and shops A 6 levels, row houses 2 storeys, roof terrace above. Plot and amenity positions stay indicative.",
        "metresPerPx": plan["metresPerPx"],
        "originPx": [round(frame.cx, 2), round(frame.cy, 2)],
        "boundsM": [round(v, 2) for v in (x0, y0, x1, y1)],
        "floorHeightM": 3.0,
        "terraceParapetM": 1.1,
        "roundabout": {"centre": [round(round_info[0], 2), round(round_info[1], 2)], "radiusM": round(round_info[2], 2)},
        "buildings": building_info,
        "amenities": amenity_info,
        "counts": {"trees": n_trees, "cars": n_cars, "plots": n_plots},
    }
    old = json.loads(META_PATH.read_text()) if META_PATH.exists() else {}
    meta["camera"] = old.get("camera", {})
    META_PATH.parent.mkdir(parents=True, exist_ok=True)
    META_PATH.write_text(json.dumps(meta, indent=1))
    print(f"built in {time.time() - t0:.1f}s: {len(building_info)} buildings, {n_trees} trees, {n_cars} cars -> {BLEND_PATH.name}")


if __name__ == "__main__":
    main()
