def label_font() -> str:
    for build in sorted(glob.glob(os.path.join(PROJECT, ".next*", "static", "chunks", "*.css"))):
        with open(build) as fh:
            css = fh.read()
        for face in re.findall(r"@font-face\{[^}]*\}", css):
            if "Zalando" in face and ("U+0000-00FF" in face or "U+??," in face):
                src = re.search(r"url\(\.\./media/([^)]+)\)", face)
                path = os.path.join(os.path.dirname(os.path.dirname(build)), "media", src.group(1)) if src else ""
                if os.path.exists(path):
                    return path
    return LABEL_FALLBACK


