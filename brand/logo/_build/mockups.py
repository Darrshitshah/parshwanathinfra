def page(body: str, extra_css: str = "", background: str = CHAMPAGNE) -> str:
    fonts = font_face("Display", DISPLAY_FONT) + font_face("Label", label_font())
    return (f"<!doctype html><html><head><meta charset='utf-8'><style>{fonts}{BASE_CSS}{extra_css}"
            f"body{{background:{background}}}</style></head><body>{body}</body></html>")


def main() -> None:
    os.makedirs(MOCKUPS, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    jobs = []
    for name, html in [("gate-signboard", page(gate_html())),
                       ("letterhead", page(letter_html(), LETTER_CSS, "#e9dcc2"))]:
        src = os.path.join(OUT, f"mockup-{name}.html")
        with open(src, "w") as fh:
            fh.write(html)
        jobs.append({"html": src, "png": os.path.join(MOCKUPS, f"{name}.png"), "width": 1600, "height": 1000})
    jobs_path = os.path.join(OUT, "mockup-jobs.json")
    with open(jobs_path, "w") as fh:
        json.dump(jobs, fh)
    subprocess.run(["node", RENDER, jobs_path], check=True)


if __name__ == "__main__":
    main()
