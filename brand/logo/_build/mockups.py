def gate_scene() -> str:
    """The gate: two sandstone piers, an espresso sign panel on them carrying the warm-gold lockup, iron gate leaves
    between the piers, the mark alone on a plaque on each pier."""
    w, h, ground = 1440, 860, 712
    parts = [
        f'<svg viewBox="0 0 {w} {h}" width="{w}" height="{h}" xmlns="http://www.w3.org/2000/svg" style="display:block">',
        '<defs><linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">'
        '<stop offset="0" stop-color="#f3eadb"/><stop offset="1" stop-color="#e6d6b8"/></linearGradient></defs>',
        f'<rect width="{w}" height="{ground}" fill="url(#sky)"/>',
    ]
    # Distant trees along the horizon (muted, behind everything)
    for cx, r, tone in [(60, 70, "#cfbf98"), (150, 52, "#c6b48a"), (1290, 64, "#cfbf98"), (1380, 80, "#c6b48a"),
                        (1200, 44, "#c6b48a"), (250, 40, "#cfbf98")]:
        parts.append(f'<ellipse cx="{cx}" cy="{ground - r * 0.55:.0f}" rx="{r}" ry="{r * 0.9:.0f}" fill="{tone}"/>')
    parts.append(f'<rect y="{ground}" width="{w}" height="{h - ground}" fill="#d8c59d"/>')
    parts.append(f'<polygon points="600,{ground} 840,{ground} 1010,{h} 430,{h}" fill="#c9b58c"/>')
    parts.append(f'<rect y="{ground}" width="{w}" height="3" fill="#bca87f"/>')

    panel_x0, panel_x1, panel_y0, panel_y1 = 230, 1210, 118, 318
    piers = [(262, 402), (1038, 1178)]
    # Gate leaves between the piers (behind the piers)
    gx0, gx1, gy0 = piers[0][1], piers[1][0], 420
    # Two leaves, each with a stile at both ends and evenly spaced bars between them
    mid, per_leaf, stile = (gx0 + gx1) / 2, 11, 8
    bars = []
    for a, b in ((gx0, mid), (mid, gx1)):
        bars += [f'<rect x="{x:.1f}" y="{gy0}" width="{stile}" height="{ground - gy0 - 14}" fill="{JEWEL}"/>'
                 for x in (a, b - stile)]
        step = (b - a - 2 * stile) / per_leaf
        bars += [f'<rect x="{a + stile + step * (i + 0.5) - 2.5:.1f}" y="{gy0}" width="5" height="{ground - gy0 - 14}" '
                 f'fill="{JEWEL}"/>' for i in range(per_leaf)]
    parts.append(f'<g>{"".join(bars)}'
                 f'<rect x="{gx0}" y="{gy0}" width="{gx1 - gx0}" height="9" fill="{JEWEL}"/>'
                 f'<rect x="{gx0}" y="{gy0 + 64}" width="{gx1 - gx0}" height="6" fill="{JEWEL}"/>'
                 f'<rect x="{gx0}" y="{ground - 24}" width="{gx1 - gx0}" height="9" fill="{JEWEL}"/>'
                 '</g>')
    # Ground shadows
    for x0, x1 in piers:
        parts.append(f'<ellipse cx="{(x0 + x1) / 2}" cy="{ground + 6}" rx="{(x1 - x0) * 0.75:.0f}" ry="10" '
                     f'fill="{ESPRESSO}" fill-opacity=".14"/>')
    # Piers: sandstone, lit from the left (the right face a shade darker), an otla-like plinth at the foot
    for x0, x1 in piers:
        pw = x1 - x0
        parts.append(f'<rect x="{x0}" y="{panel_y1}" width="{pw}" height="{ground - panel_y1}" fill="{SAND}"/>')
        parts.append(f'<rect x="{x1 - pw * 0.22:.0f}" y="{panel_y1}" width="{pw * 0.22:.0f}" height="{ground - panel_y1}" fill="#c9b58b"/>')
        parts.append(f'<rect x="{x0 - 14}" y="{ground - 30}" width="{pw + 28}" height="30" fill="#cdb98f"/>')
        parts.append(f'<rect x="{x0 - 14}" y="{ground - 30}" width="{pw + 28}" height="4" fill="#e6d6b4"/>')
        # Plaque with the mark alone
        px, py, pw2, ph = x0 + (pw - 84) / 2 - pw * 0.06, 430, 84, 108
        parts.append(f'<rect x="{px:.0f}" y="{py}" width="{pw2}" height="{ph}" rx="3" fill="{ESPRESSO}"/>')
        parts.append(logo("mark-warm-gold.svg", px + pw2 / 2, py + 24, 60))
    # The sign panel on the piers: coping, espresso face, a fine warm-gold inset rule, the lockup
    parts.append(f'<rect x="{panel_x0 - 16}" y="{panel_y0 - 18}" width="{panel_x1 - panel_x0 + 32}" height="18" fill="#cdb98f"/>')
    parts.append(f'<rect x="{panel_x0 - 16}" y="{panel_y0 - 18}" width="{panel_x1 - panel_x0 + 32}" height="4" fill="#e6d6b4"/>')
    parts.append(f'<rect x="{panel_x0}" y="{panel_y0}" width="{panel_x1 - panel_x0}" height="{panel_y1 - panel_y0}" fill="{ESPRESSO}"/>')
    parts.append(f'<rect x="{panel_x0 + 16}" y="{panel_y0 + 16}" width="{panel_x1 - panel_x0 - 32}" '
                 f'height="{panel_y1 - panel_y0 - 32}" fill="none" stroke="{WARM_GOLD}" stroke-opacity=".45" stroke-width="1.5"/>')
    parts.append(f'<rect x="{panel_x0}" y="{panel_y1 - 6}" width="{panel_x1 - panel_x0}" height="6" fill="#120e0a" fill-opacity=".5"/>')
    lockup_h = 96
    parts.append(logo("horizontal-warm-gold.svg", (panel_x0 + panel_x1) / 2, (panel_y0 + panel_y1) / 2 - lockup_h / 2, lockup_h))
    parts.append("</svg>")
    return "".join(parts)


