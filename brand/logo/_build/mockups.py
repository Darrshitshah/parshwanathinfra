def font_face(family: str, path: str) -> str:
    with open(path, "rb") as fh:
        data = base64.b64encode(fh.read()).decode("ascii")
    kind = ("font/woff2", "woff2") if path.endswith(".woff2") else ("font/ttf", "truetype")
    return f"@font-face{{font-family:{family};font-weight:100 900;src:url(data:{kind[0]};base64,{data}) format('{kind[1]}');}}"


def logo(name: str, x: float, y: float, height: float) -> str:
    """A brand SVG placed inside a parent SVG at (x, y), `height` user units tall (width from its viewBox)."""
    with open(os.path.join(SVG, name)) as fh:
        s = fh.read().strip()
    s = re.sub(r"<title>.*?</title>", "", s)
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', s).group(1).split()]
    width = height * vb[2] / vb[3]
    return s.replace("<svg ", f'<svg x="{x - width / 2:.2f}" y="{y:.2f}" width="{width:.2f}" height="{height:.2f}" ', 1)


def logo_html(name: str, height: float) -> str:
    with open(os.path.join(SVG, name)) as fh:
        s = fh.read().strip()
    s = re.sub(r"<title>.*?</title>", "", s)
    return s.replace("<svg ", f'<svg style="display:block;height:{height}px;width:auto" ', 1)


