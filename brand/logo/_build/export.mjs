// Second step of the logo build (run after build.py), with the project's own svgo and sharp (no installs):
//   1. optimises brand/logo/svg/*.svg with svgo (two decimals, title and role kept; the favicon files are left as
//      written because svgo would inline the fill and break their dark-mode media query),
//   2. writes src/components/ui/logo-data.ts from _build/out/site-{mark,word}.svg (one decimal),
//   3. renders the PNG exports and icons listed in _build/out/png-jobs.json into brand/logo/png/,
//   4. packs favicon.ico (16, 32, 48) into brand/logo/png/ and src/app/.
// Usage (from the project folder): node brand/logo/_build/export.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PROJECT = join(HERE, "..", "..", "..");
const require = createRequire(join(PROJECT, "package.json"));
const { optimize } = require("svgo");
const sharp = require("sharp");

const SVG_DIR = join(PROJECT, "brand", "logo", "svg");
const OUT = join(HERE, "out");
const SITE_DATA = join(PROJECT, "src", "components", "ui", "logo-data.ts");
const APP_FAVICON = join(PROJECT, "src", "app", "favicon.ico");
const KEEP_AS_WRITTEN = new Set(["favicon.svg"]);

function svgoConfig(precision) {
  return {
    multipass: true,
    floatPrecision: precision,
    plugins: [{ name: "preset-default", params: { overrides: { removeUnknownsAndDefaults: false } } }],
  };
}

function optimiseBrandSvgs() {
  for (const file of readdirSync(SVG_DIR).filter((name) => name.endsWith(".svg"))) {
    if (KEEP_AS_WRITTEN.has(file)) continue;
    const path = join(SVG_DIR, file);
    const result = optimize(readFileSync(path, "utf8"), { path, ...svgoConfig(2) });
    writeFileSync(path, `${result.data}\n`);
  }
}

function pathData(file, precision) {
  const svg = optimize(readFileSync(join(OUT, file), "utf8"), svgoConfig(precision)).data;
  const match = svg.match(/ d="([^"]+)"/);
  const box = svg.match(/viewBox="0 0 ([\d.]+) 100"/);
  if (!match || !box) throw new Error(`no path or viewBox in ${file}`);
  return { d: match[1], width: Number(box[1]) };
}

function writeSiteData() {
  const geometry = JSON.parse(readFileSync(join(OUT, "geometry.json"), "utf8"));
  const mark = pathData("site-mark.svg", 1);
  const word = pathData("site-word.svg", 1);
  const body = `/**
 * Parshwanath Infra logo outlines (05 Sheltering Arch). GENERATED by brand/logo/_build (build.py, export.mjs): do not
 * edit by hand; change the geometry there and rebuild.
 *
 * Units: the mark is 100 units tall. The wordmark uses the same vertical units (its viewBox is also 100 tall), so the
 * mark and the name drawn as two SVGs of the same CSS height keep the lockup's alignment: the cap top of PARSHWANATH
 * on the arch's springline and INFRA on the otla's ground line. LOGO_GAP is the space between them, in mark heights.
 */

export interface LogoShape {
  /** viewBox width; the viewBox height is always 100. */
  width: number;
  d: string;
}

export const LOGO_MARK: LogoShape = {
  width: ${mark.width},
  d: "${mark.d}",
};

export const LOGO_WORD: LogoShape = {
  width: ${word.width},
  d: "${word.d}",
};

export const LOGO_GAP = ${geometry.site_gap.toFixed(4)};
`;
  writeFileSync(SITE_DATA, body);
  return body.length;
}

async function renderPngs() {
  const { out, jobs } = JSON.parse(readFileSync(join(OUT, "png-jobs.json"), "utf8"));
  mkdirSync(out, { recursive: true });
  const rendered = {};
  for (const job of jobs) {
    const svg = job.inline ?? readFileSync(job.svg, "utf8");
    const box = svg.match(/viewBox="([-\d.]+) ([-\d.]+) ([\d.]+) ([\d.]+)"/);
    if (!box) throw new Error(`no viewBox for ${job.png}`);
    const [vw, vh] = [Number(box[3]), Number(box[4])];
    const width = job.width ?? Math.round((job.height * vw) / vh);
    const height = job.height ?? Math.round((job.width * vh) / vw);
    // Render big enough, then resize to the exact size (librsvg sizes an SVG by its viewBox at 72 dpi).
    const density = Math.min(2400, Math.max(72, (72 * width * 2) / vw));
    const png = await sharp(Buffer.from(svg), { density })
      .resize(width, height, { fit: "fill" })
      .png({ compressionLevel: 9, palette: false })
      .toBuffer();
    writeFileSync(join(out, job.png), png);
    rendered[job.png] = png;
  }
  return { out, rendered };
}

/** ICO with PNG payloads (Windows Vista and later, every current browser). */
function packIco(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  const entries = [];
  let offset = 6 + 16 * images.length;
  for (const { size, data } of images) {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size >= 256 ? 0 : size, 0);
    entry.writeUInt8(size >= 256 ? 0 : size, 1);
    entry.writeUInt8(0, 2);
    entry.writeUInt8(0, 3);
    entry.writeUInt16LE(1, 4);
    entry.writeUInt16LE(32, 6);
    entry.writeUInt32LE(data.length, 8);
    entry.writeUInt32LE(offset, 12);
    entries.push(entry);
    offset += data.length;
  }
  return Buffer.concat([header, ...entries, ...images.map((image) => image.data)]);
}

optimiseBrandSvgs();
const siteBytes = writeSiteData();
const { out, rendered } = await renderPngs();
const ico = packIco([16, 32, 48].map((size) => ({ size, data: rendered[`favicon-${size}.png`] })));
writeFileSync(join(out, "favicon.ico"), ico);
writeFileSync(APP_FAVICON, ico);
console.log(`svgs optimised, logo-data.ts ${siteBytes} bytes, ${Object.keys(rendered).length} pngs, favicon.ico ${ico.length} bytes`);
